#For Loop
# for loop – use when you know how many times to loop

# Used for:
# Going through a list, string, or dictionary
# Repeating a fixed number of times (range)
# Processing multiple items (e.g., user list, feedback list)
for i in range(1,10):
    print(i)

for a in range(1,10,2):
    print(a) # output is 1,3,5,7,9
