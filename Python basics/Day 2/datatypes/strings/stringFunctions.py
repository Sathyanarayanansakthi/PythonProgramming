#Stirng ]is a sequence of characters, like letters, numbers, and symbols, that is treated as a single piece of data

"""| Method               | Description                                          |
| -------------------- | ---------------------------------------------------- |
| `.upper()`           | Converts the string to all uppercase letters         |
| `.lower()`           | Converts the string to all lowercase letters         |
| `.title()`           | Capitalizes the first letter of every word           |
| `.capitalize()`      | Capitalizes the first letter of the string           |
| `.split()`           | Splits the string into a list                        |
| `.rsplit()`          | Splits the string into a list from the right         |
| `.strip()`           | Removes whitespace from the beginning and end        |
| `.replace(old, new)` | Replaces a substring with another                    |
| `.find(sub)`         | Finds the index of a substring                       |
| `.startswith()`      | Checks if the string starts with a certain substring |
| `.endswith()`        | Checks if the string ends with a certain substring   |
"""

name="Sathya Narayanan"
print(name)
print(name.upper())
print(name.lower())
print(name.title())
print(name.capitalize())
print(name.split())
print(name.rsplit())
