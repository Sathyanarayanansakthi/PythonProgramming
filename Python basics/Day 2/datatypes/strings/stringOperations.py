firstName="Sathya"
lastName="Narayanan"
print(firstName)
print(lastName)

#Concatenation
print(firstName+lastName) #SathyaNarayanan
print(firstName.upper()+lastName.upper())#SATHYANARAYANAN
print(firstName+lastName.lower())#Sathyanarayanan
print(firstName+" "+lastName) #Sathya Narayanan

#Repetition
Greeting="Hello"
print(Greeting*2) #HelloHello

#Slicing
firstName="Sathya"
print(firstName[::-1]) #Reverse the letters
print(firstName[:-1])  #Removing the last element

