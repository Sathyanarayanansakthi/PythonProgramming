#Looping is a process of repeating the block of code

# for loop is used when the number of iterations is known or when iterating over a sequence of elements
for i in range(5):
    print(i)

for k in  range(1,10): #Inital is 1 and Ending is 10
    print(k)

for j in range(1,10,2): # Inital is 1 and ending is 10 and  step value is 2 it will add
    print(j)



