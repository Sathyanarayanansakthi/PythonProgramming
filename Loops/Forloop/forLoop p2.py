# Print multiplication table of 5

for i in range(0,11):
    print(f"5 x {i} = {i * 5}")

# Print each character in the string "Python"
for char in "Python":
    print(char)

# Find the sum of numbers from 1 to 11
total = 0
for j in range(1,11):
    total += j
print("Sum:", total)

#Print all Even Numbers form 1 to 50
for s in range(0,51,2):
    print(s)
#Using If Statement
for s in range(1,51):
    if s % 2 == 0:
        print(s)

#Print all Odd numbers form 1 to 50
for k in range(1,51,2):
    print(k)

#Using if Statement
for k in range(0,50,1):
    if k % 2 != 0:
        print(k)

# Print 7 Table
for ji in range(1,11):
    print(f"7X {ji} = {ji*7}")