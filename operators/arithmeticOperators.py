# Arithmetic Operators are used to perform basic mathematical operations

# Addition means adding two or more values 
a = 1
b = 2
c = a + b
print(c) 

sum = 2 + 2
print(sum)  

# Subtraction means subtracting two or more values 
sub = 1 - 2
print(sub)  

ab = 101
bc = 12
cd = ab - bc
print(cd)  

# Multiplication means multiplying two or more values 
sa = 10
ad = 10
sad = sa * ad
print(sad) 

happy = 10 * 2
print(happy)  

# Division means dividing two or more values (returns float)
print(2 / 2)  

sa = 1290
s = 6
asa = sa / s
print(asa)  

# Floor Division means dividing and returning only the whole number part (ignores decimal)
print(5 // 2)  # Output: 2

# Modulus means returning the remainder after division
print(5 % 2)  # Output: 1

# Exponentiation means raising a number to a power
print(2 ** 3)  # Output: 8
