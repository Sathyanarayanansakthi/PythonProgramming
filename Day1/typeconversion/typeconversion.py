# Typecasting means converting one data type into another, like changing a string into an integer, a float into an integer, etc.

name="SN" 
age=21
gpa=7.5
is_Student=True

print(type(gpa))
print(type(age))
print(type(name))
print(type(is_Student))


#converting float to int
gpa =int(gpa)
print(gpa)

#converting to string
gpa =str(gpa);
print(gpa)

#converting to float
age =float(age);print(age)

#converting string to boolean
name=bool(name)
print(name)

#converting boolean to string 
is_Student=str(is_Student)
print(is_Student)